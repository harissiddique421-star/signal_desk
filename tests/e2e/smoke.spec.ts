import { expect, test } from "@playwright/test";

test.describe("Signal Desk smoke", () => {
  test("safe defaults with no live provider configured", async ({ page }) => {
    const errors: string[] = [];
    page.on("pageerror", (e) => errors.push(e.message));
    await page.goto("/");

    await expect(page.getByRole("heading", { name: "Signal Desk" })).toBeVisible();
    await expect(page.getByText("Live data unavailable — no live signals will be generated.")).toBeVisible();
    await expect(page.getByTestId("verdict")).toHaveText("NO TRADE");

    // Sample provider is selected and clearly labelled as synthetic
    await expect(page.getByLabel("Data source")).toHaveValue("sample");
    await page.getByRole("button", { name: "Analyse now" }).click();
    await expect(page.getByText("Sample data — not a signal")).toBeVisible();
    await expect(page.getByTestId("verdict")).toHaveText("NO TRADE");
    await expect(page.getByText(/is not a verified live market feed/).first()).toBeVisible();

    // OTC warning
    await page.getByRole("button", { name: "OTC", exact: true }).first().click();
    await expect(page.getByText(/OTC quotes are generated by the broker/)).toBeVisible();

    // Screenshot tab states the limitation
    await page.getByRole("tab", { name: "Screenshot" }).click();
    await expect(page.getByText("Screenshot interpretation is not implemented.", { exact: false })).toBeVisible();

    // Sources tab shows provider health honestly
    await page.getByRole("tab", { name: "Sources" }).click();
    await expect(page.getByRole("tabpanel").getByText("TWELVEDATA_API_KEY is not set")).toBeVisible();

    expect(errors).toEqual([]);
  });

  test("no horizontal overflow", async ({ page }) => {
    await page.goto("/");
    await page.getByRole("button", { name: "Analyse now" }).click();
    await expect(page.getByTestId("verdict")).toHaveText("NO TRADE");
    const [sw, vw] = await page.evaluate(() => [document.documentElement.scrollWidth, window.innerWidth]);
    expect(sw).toBeLessThanOrEqual(vw);
  });

  test("manifest is served for PWA install", async ({ request }) => {
    const r = await request.get("/manifest.webmanifest");
    expect(r.ok()).toBe(true);
    const m = await r.json();
    expect(m.display).toBe("standalone");
    expect(m.icons.length).toBeGreaterThanOrEqual(2);
  });
});
