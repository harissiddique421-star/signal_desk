"use client";

import type { HealthResponse } from "@/lib/api/contracts";
import { fmtTime } from "@/lib/client/format";

const STATUS: Record<string, { label: string; cls: string }> = {
  OK: { label: "Working", cls: "text-call" },
  NOT_CONFIGURED: { label: "Not configured", cls: "text-hold" },
  DEGRADED: { label: "Degraded", cls: "text-warn" },
  DOWN: { label: "Down", cls: "text-put" },
};

/** Research summary — see docs/DATA_SOURCES.md for detail and how this was checked. */
const COMPARISON = [
  { name: "Twelve Data", adapter: "Implemented", coverage: "Regular FX pairs, 1-minute bars over REST", otc: "No", notes: "Free and paid tiers with credit limits; check current pricing and terms." },
  { name: "OANDA v20 API", adapter: "Planned", coverage: "Broker FX/CFD candles incl. M1 with bid/ask", otc: "No", notes: "Needs an OANDA account and token; availability varies by country." },
  { name: "Polygon.io forex", adapter: "Planned", coverage: "FX aggregates and quotes", otc: "No", notes: "Real-time data is on paid plans; check current naming, pricing and terms." },
  { name: "Quotex", adapter: "Not possible", coverage: "No public market-data API", otc: "Broker-internal", notes: "OTC prices are generated by the broker. Unofficial scrapers or private APIs are not used." },
];

export function SourcesPanel({ health, error }: { health: HealthResponse | null; error: string | null }) {
  return (
    <div className="space-y-6">
      {error && <p role="alert" className="text-put">Source health unavailable: {error}</p>}
      {health && (
        <ul className="grid gap-3 sm:grid-cols-2">
          {health.providers.map((p) => (
            <li key={p.id} className="glass-quiet p-4">
              <div className="flex items-baseline justify-between gap-2">
                <span className="font-semibold">{p.name}</span>
                <span className={`text-sm ${STATUS[p.status].cls}`}>{STATUS[p.status].label}</span>
              </div>
              <p className="mt-1 text-sm text-muted">{p.detail}</p>
              <p className="mt-2 text-xs text-faint">
                {p.verified ? "Real market feed" : "Synthetic test data"}, covers {p.supportedMarketTypes.map((m) => (m === "LIVE" ? "regular" : "OTC")).join(" and ")}
                {p.latencyMs !== null ? `, last latency ${p.latencyMs} ms` : ""}, checked {fmtTime(p.checkedAt, true)}
              </p>
            </li>
          ))}
        </ul>
      )}

      {health && (
        <ul className="space-y-2 text-sm">
          <li>
            <span className="font-semibold">OTC data: </span>
            <span className="text-muted">{health.otcNote}</span>
          </li>
          <li>
            <span className="font-semibold">News / economic calendar: </span>
            <span className="text-muted">No verified provider configured. Signals carry a warning that news risk was not checked; set the rule “requireNewsFilter” to block trading instead.</span>
          </li>
        </ul>
      )}

      <div>
        <h3 className="font-semibold">Provider comparison</h3>
        <p className="mt-1 text-sm text-faint" lang="ur-Latn">
          Normal FX feed Quotex OTC ki keemat nahin dikhata. OTC ke liye koi jaiz (permitted) data source mojood nahin.
        </p>
        <div className="relative mt-3 overflow-x-auto">
          <table className="w-full min-w-[640px] text-left text-sm">
            <thead className="text-muted">
              <tr>
                <th className="py-2 pr-3 font-medium">Provider</th>
                <th className="py-2 pr-3 font-medium">Adapter</th>
                <th className="py-2 pr-3 font-medium">Coverage</th>
                <th className="py-2 pr-3 font-medium">OTC</th>
                <th className="py-2 pr-3 font-medium">Notes</th>
              </tr>
            </thead>
            <tbody>
              {COMPARISON.map((c) => (
                <tr key={c.name} className="border-t border-white/5 align-top">
                  <td className="py-2 pr-3 font-medium">{c.name}</td>
                  <td className="py-2 pr-3">{c.adapter}</td>
                  <td className="py-2 pr-3 text-muted">{c.coverage}</td>
                  <td className="py-2 pr-3 text-muted">{c.otc}</td>
                  <td className="py-2 pr-3 text-muted">{c.notes}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </div>
    </div>
  );
}
